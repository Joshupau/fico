// Writes public/sw.js from scripts/sw.source.js with this build's id baked in (BUILD_ID is never
// read; it only makes each deploy's sw.js differ).
//
// The browser only sees a new version of the app when sw.js changes byte for byte, so every deploy
// stamps its commit (or the build time) into it. The new worker then installs and waits, and the app
// shows its "update available" bar instead of switching versions under the user.
import { readFileSync, writeFileSync } from 'node:fs'

const id = process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || `local-${Date.now()}`
const source = readFileSync('scripts/sw.source.js', 'utf8')
writeFileSync(
  'public/sw.js',
  `// GENERATED by scripts/build-sw.mjs from scripts/sw.source.js. Do not edit.\nconst BUILD_ID = '${id.slice(0, 12)}'\n${source}`
)
console.log(`[sw] wrote public/sw.js (build ${id.slice(0, 12)})`)
